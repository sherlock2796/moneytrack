export function getLang() { return lang; }
export function t(key, vars) {
  let s = (dict[lang] && dict[lang][key]) ?? dict.it[key] ?? key;
  if (vars) for (const k in vars) s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
  return s;
}
